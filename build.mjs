/** Commit the runtime bundle so Git installations never need dependency links or install scripts. */
import { build } from 'esbuild'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = dirname(fileURLToPath(import.meta.url))
const result = await build({
  absWorkingDir: root, entryPoints: ['index.js'], outfile: 'dist/index.js',
  bundle: true, platform: 'node', format: 'esm', target: 'node24', metafile: true,
  legalComments: 'none',
  banner: { js: '// Generated by npm run build; dependency licenses: ../THIRD_PARTY_NOTICES.txt\nimport { createRequire as __createRequire } from "node:module";\nconst require = __createRequire(import.meta.url);' },
})
const packages = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.startsWith('node_modules/')) continue
  let dir = dirname(resolve(root, input))
  while (dir !== root) {
    let pkg
    try { pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8')) }
    catch (error) { if (error.code !== 'ENOENT') throw error }
    if (pkg) { packages.set(pkg.name, { dir, pkg }); break }
    dir = dirname(dir)
  }
}
const notices = []
for (const [name, { dir, pkg }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const license = (await readdir(dir)).find(file => /^licen[cs]e(?:[.-].*)?$/i.test(file))
  if (!license) throw new Error('Missing license for bundled dependency: ' + name)
  notices.push(`${name}@${pkg.version} (${pkg.license})\n${await readFile(join(dir, license), 'utf8')}`.trim())
}
await writeFile(join(root, 'THIRD_PARTY_NOTICES.txt'), notices.join('\n\n---\n\n') + '\n')
console.log('Built dependency-contained ESM runtime with ' + packages.size + ' dependency licenses')
